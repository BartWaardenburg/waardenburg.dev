// Turns the logo files in public/logos into alpha masks, so the page can paint them.
// Each mask is a white shape on a transparent ground, trimmed to the logo.
// Run: node scripts/generate-logo-masks.mjs
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const SRC = 'public/logos';
const OUT = 'public/logos/paint';
const HEIGHT = 240;
const WHITE = 232;
const SOFT = 40;
/** A logo with less colour than this is a white logo; its white is the shape, not a gap. */
const MIN_COLOUR_SHARE = 0.03;

const files = (await readdir(SRC)).filter((f) => /\.(svg|png)$/.test(f)).sort();
await mkdir(OUT, { recursive: true });

const entries = [];
for (const file of files) {
	const name = path.parse(file).name;
	const { data, info } = await sharp(path.join(SRC, file), { density: 400 })
		.resize({ height: HEIGHT })
		.ensureAlpha()
		.raw()
		.toBuffer({ resolveWithObject: true });

	let opaque = 0;
	let coloured = 0;
	for (let i = 0; i < data.length; i += 4) {
		if (data[i + 3] < 128) continue;
		opaque += 1;
		if (Math.min(data[i], data[i + 1], data[i + 2]) < WHITE) coloured += 1;
	}
	// in a logo with colour, white parts are gaps: knock them out of the mask
	const knockOutWhite = coloured / Math.max(1, opaque) > MIN_COLOUR_SHARE;

	const mask = Buffer.alloc(data.length);
	for (let i = 0; i < data.length; i += 4) {
		let alpha = data[i + 3];
		if (knockOutWhite) {
			const lightest = Math.min(data[i], data[i + 1], data[i + 2]);
			const keep = Math.min(
				1,
				Math.max(0, (WHITE + SOFT / 2 - lightest) / SOFT),
			);
			alpha = Math.round(alpha * keep);
		}
		mask[i] = 255;
		mask[i + 1] = 255;
		mask[i + 2] = 255;
		mask[i + 3] = alpha;
	}

	const out = await sharp(mask, {
		raw: { width: info.width, height: info.height, channels: 4 },
	})
		.trim({ threshold: 1 })
		.png({ palette: true, colours: 16, compressionLevel: 9 })
		.toBuffer({ resolveWithObject: true });
	await writeFile(path.join(OUT, `${name}.png`), out.data);
	entries.push({
		key: `/logos/${file}`,
		src: `/logos/paint/${name}.png`,
		ratio: Number((out.info.width / out.info.height).toFixed(3)),
	});
}

const body = entries
	.map((e) => `\t'${e.key}': { src: '${e.src}', ratio: ${e.ratio} },`)
	.join('\n');
await writeFile(
	'src/lib/logoMasks.ts',
	`// Generated by scripts/generate-logo-masks.mjs. Do not edit by hand.\n\nexport interface LogoMask {\n\tsrc: string;\n\t/** width divided by height */\n\tratio: number;\n}\n\nexport const logoMasks: Record<string, LogoMask> = {\n${body}\n};\n`,
);
console.log(`wrote ${entries.length} masks`);
